_BY_CODE: dict[SpecialistSkillCode, SpecialistSkillDefinition] | None = None


def _index() -> dict[SpecialistSkillCode, SpecialistSkillDefinition]:
    global _BY_CODE
    if _BY_CODE is None:
        _BY_CODE = {item.code: item for item in _definitions()}
    return _BY_CODE


def list_skills() -> list[SpecialistSkillDefinition]:
    return list(_index().values())


def get_skill(code: SpecialistSkillCode | str) -> SpecialistSkillDefinition | None:
    if isinstance(code, str):
        try:
            code = SpecialistSkillCode(code)
        except ValueError:
            return None
    return _index().get(code)
