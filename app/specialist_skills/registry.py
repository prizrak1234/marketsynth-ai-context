def _skill(
    *,
    code: SpecialistSkillCode,
    title: str,
    domain: KnowledgeDomain,
    roles: list[str],
    description: str,
    inputs: list[str],
    outputs: list[str],
    clarifications: list[str],
    knowledge_scopes: list[str],
    quality_gates: list[str],
    required_tools: list[str] | None = None,
    optional_tools: list[str] | None = None,
    prerequisites: list[str] | None = None,
) -> SpecialistSkillDefinition:
    return SpecialistSkillDefinition(
        id=f"skill.{code.value}.v1",
        code=code,
        version="1.0",
        title=title,
        domain=domain,
        description=description,
        specialist_roles=roles,
        input_schema=inputs,
        output_schema=outputs,
        prerequisites=prerequisites or [],
        clarification_schema=clarifications,
        knowledge_scopes=knowledge_scopes,
        required_tools=required_tools or [],
        optional_tools=optional_tools or ["knowledge_search"],
        quality_gates=quality_gates,
        execution_policy=SpecialistSkillExecutionPolicy.DRAFT_ONLY,
        status=SpecialistSkillStatus.DRAFT,
        supersedes_version=None,
    )


